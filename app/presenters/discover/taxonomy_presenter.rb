  def self.taxonomy_label(slug, locale: I18n.locale)
    return if slug.blank?

    if locale.to_s == "am"
      TAXONOMY_AMHARIC_LABELS[slug] || TAXONOMY_LABELS[slug] || slug
    else
      TAXONOMY_LABELS[slug] || slug
    end
  end

  def taxonomies_for_nav(recommended_products: nil)
    taxonomies = Rails.cache.fetch("taxonomies_for_nav", expires_in: 1.hour) do
      Taxonomy.all.eager_load(:taxonomy_stat).sort_by do |taxonomy|
        if taxonomy.slug == "other"
          [1, taxonomy.slug]
        else
          [-taxonomy.taxonomy_stat&.recent_sales_count.to_i, taxonomy.slug]
        end
      end.map do |taxonomy|
        {
          key: taxonomy.id.to_s,
          label: TAXONOMY_LABELS[taxonomy.slug],
          slug: taxonomy.slug,
          parent_key: taxonomy.parent_id&.to_s
        }
      end
    end

    if I18n.locale.to_s == "am"
      taxonomies = taxonomies.map do |taxonomy|
        taxonomy.merge(label: self.class.taxonomy_label(taxonomy[:slug], locale: :am))
      end
    end

    taxonomy_ids = recommended_products&.filter_map(&:taxonomy_id)
    if taxonomy_ids.present?
      sorted_roots = (Taxonomy.includes(:self_and_ancestors).where(self_and_ancestors: { parent_id: nil }).find(taxonomy_ids)).each_with_object({}).with_index do |(taxonomy, hash), index|
        hash[taxonomy.self_and_ancestors.first.slug] ||= taxonomy_ids.size - index
      end
      taxonomies = taxonomies.sort_by.with_index { |taxonomy, index| [-(sorted_roots[taxonomy[:slug]] || 0), index] }
    end

    taxonomies
  end

  # The Discover nav wants taxonomies in sales-popularity order, but the product editor's
  # category picker is a lookup of a category the seller already has in mind, so it lists
  # them alphabetically by the breadcrumb the picker displays ("3D > 3D Assets > 3ds Max"),
  # keeping each root next to its descendants.
  def taxonomies_for_category_picker
    taxonomies = taxonomies_for_nav
    taxonomies_by_key = taxonomies.index_by { |taxonomy| taxonomy[:key] }
    breadcrumbs = {}
    taxonomies.sort_by do |taxonomy|
      hierarchy_for_taxonomy(taxonomy, taxonomies_by_key, breadcrumbs, attribute: :label, separator: " > ").downcase
    end
  end

  def categories_for_api
    categories_by_id.values.sort_by { |category| category[:path] }
  end

  def categories_by_id_for_api
    categories_by_id
  end

  def category_for_taxonomy_id(taxonomy_id)
    return if taxonomy_id.blank?

    categories_by_id[taxonomy_id.to_s]
  end

  def category_for_path(path)
    return if path.blank?

    categories_by_path[path]
  end

  private
    def categories_by_path
      @categories_by_path ||= categories_by_id.values.index_by { |category| category[:path] }
    end

    def categories_by_id
      @categories_by_id ||= begin
        taxonomies = taxonomies_for_nav
        taxonomies_by_id = taxonomies.index_by { |taxonomy| taxonomy[:key] }
        path_by_id = {}

        taxonomies.each_with_object({}) do |taxonomy, hash|
          hash[taxonomy[:key]] = {
            id: taxonomy[:key].to_i,
            name: taxonomy[:slug],
            label: taxonomy[:label] || taxonomy[:slug],
            path: path_for_taxonomy(taxonomy, taxonomies_by_id, path_by_id),
            parent_id: taxonomy[:parent_key]&.to_i
          }
        end
      end
    end

    def path_for_taxonomy(taxonomy, taxonomies_by_id, path_by_id)
      hierarchy_for_taxonomy(taxonomy, taxonomies_by_id, path_by_id, attribute: :slug, separator: "/")
    end

    # Joins `attribute` from the root down to `taxonomy` (e.g. "3d/3d-assets" or "3D > 3D Assets"),
    # memoizing each taxonomy's result in `cache` so shared ancestors are only walked once.
    def hierarchy_for_taxonomy(taxonomy, taxonomies_by_key, cache, attribute:, separator:)
      cache[taxonomy[:key]] ||= begin
        parent = taxonomies_by_key[taxonomy[:parent_key]]
        value = taxonomy[attribute].to_s
        parent ? "#{hierarchy_for_taxonomy(parent, taxonomies_by_key, cache, attribute:, separator:)}#{separator}#{value}" : value
      end
    end
end
